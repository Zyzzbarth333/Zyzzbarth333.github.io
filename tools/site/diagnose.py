# The published pages are the tracked HTML pages outside assets/; the indexable ones are those not marked noindex.
# sitemap.xml should list exactly the indexable ones, robots.txt should name the sitemap and block nothing, and each
# indexable page should carry one canonical link to its own address.
def noindex(p):
    return bool(re.search(r'<meta\s+name="robots"\s+content="[^"]*noindex', p.read_text(errors='replace'), re.I))


