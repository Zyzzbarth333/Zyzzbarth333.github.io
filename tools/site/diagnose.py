class PagesLike(SimpleHTTPRequestHandler):
    """Serves the repo as GitHub Pages does where the checks care: text gzipped, and a 10-minute cache header."""
    TEXT = ('.html', '.css', '.js', '.mjs', '.json', '.svg', '.txt', '.xml', '.webmanifest')

    def __init__(self, *a, **k):
        super().__init__(*a, directory=str(REPO), **k)

    def log_message(self, *a):
        pass

    def end_headers(self):
        self.send_header('Cache-Control', 'max-age=600')
        super().end_headers()

    def send_head(self):
        path = self.translate_path(self.path)
        if path.endswith(self.TEXT) and os.path.isfile(path) and 'gzip' in self.headers.get('Accept-Encoding', ''):
            body = gzip.compress(Path(path).read_bytes(), 6)
            self.send_response(200)
            self.send_header('Content-Type', self.guess_type(path))
            self.send_header('Content-Encoding', 'gzip')
            self.send_header('Content-Length', str(len(body)))
            self.end_headers()
            return io.BytesIO(body)
        return super().send_head()


