class Refs(html.parser.HTMLParser):
    """Every reference (href, src, srcset, poster, SVG image href) and the visible text, alt and title text."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.refs, self.text, self.skip = [], [], 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ('script', 'style', 'svg'):
            self.skip += 1
        for k in ('href', 'src', 'poster', 'xlink:href', 'data'):
            if a.get(k):
                self.refs.append((tag, a[k]))
        if a.get('srcset'):
            self.refs += [(tag, s.strip().split(' ')[0]) for s in a['srcset'].split(',') if s.strip()]
        for k in ('alt', 'title', 'aria-label', 'content'):
            if a.get(k):
                self.text.append(a[k])

    def handle_endtag(self, tag):
        if tag in ('script', 'style', 'svg') and self.skip:
            self.skip -= 1

    def handle_data(self, d):
        if not self.skip:
            self.text.append(d)


def parse(p):
    r = Refs()
    r.feed(p.read_text(encoding='utf-8', errors='replace'))
    return r


def local_target(src_file, ref):
    """The repo file a local reference points at (None for external, mail, data and in-page links), and its ?v= tag."""
    s = urlsplit(ref)
    if s.scheme or ref.startswith(('#', '//', 'data:', 'mailto:', 'tel:', 'javascript:')) or not s.path:
        return None, None
    path = unquote(s.path)
    base = REPO if path.startswith('/') else src_file.parent
    t = (base / path.lstrip('/')).resolve()
    if t.is_dir():
        t = t / 'index.html'
    v = re.search(r'(?:^|&)v=([0-9a-f]{8})', s.query or '')
    return t, v.group(1) if v else None


sha8 = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()[:8]
links = {'checked': 0, 'broken': 0, 'stale_tags': 0, 'external': {}}
deps = {}                                       # file -> set of local files it loads

def scan(p):
    parsed = parse(p)
    files = set()
    for tag, ref in parsed.refs:
        t, v = local_target(p, ref)
        if t is None:
            if urlsplit(ref).scheme in ('http', 'https'):
                links['external'].setdefault(ref, set()).add(rel(p))
            continue
        links['checked'] += 1
        if not t.exists():
            links['broken'] += 1
            issue('fail', 'links', rel(p), f'<{tag}> points at {ref}, which does not exist')
            continue
        if v and v != sha8(t):
            links['stale_tags'] += 1
            issue('warn', 'links', rel(p), f'{ref}: the ?v= tag is stale (file is {sha8(t)}): rebuild')
        if tag != 'a':
            files.add(t)
    deps[p] = files
    return parsed


css_deps = {}
for css in sorted((REPO / 'assets/css').glob('*.css')):
    found = set()
    for ref in re.findall(r'url\(\s*["\']?([^"\')]+)', css.read_text()):
        t, _ = local_target(css, ref)
        if t is None:
            continue
        links['checked'] += 1
        if not t.exists():
            links['broken'] += 1
            issue('fail', 'links', rel(css), f'url({ref}) does not exist')
        else:
            found.add(t)
    css_deps[css.resolve()] = found

parsed = {p: scan(p) for p in pages() + figures()}


def weight(p, seen=None):
    seen = set() if seen is None else seen
    total = 0
    for f in [p] + sorted(deps.get(p, ())):
        f = f.resolve()
        if f in seen or not f.exists():
            continue
        seen.add(f)
        total += f.stat().st_size
        if f in css_deps:
            for g in css_deps[f]:
                if g not in seen:
                    seen.add(g)
                    total += g.stat().st_size
        if f != p.resolve() and f.suffix == '.html' and f in {q.resolve() for q in deps}:
            total += weight(next(q for q in deps if q.resolve() == f), seen) - f.stat().st_size
    return total


