def facts_detail():
    if facts['status'] == 'skipped':
        return 'not run'
    plural = lambda n, word: f"{n} {word}{'' if n == 1 else 's'}"
    notes = [plural(facts['held'], 'held draft') + ' not published' if facts['held'] else '',
             plural(facts['pending'], 'page') + ' naming wording that waits on an answer' if facts['pending'] else '']
    notes = ', '.join(n for n in notes if n)
    if facts['status'] == 'pass':
        return 'matches facts.yaml' + (f' ({notes})' if notes else '')
    faults = sum(1 for i in issues if i['check'] == 'facts' and i['severity'] != 'info')
    return (plural(facts['claims'], 'dropped claim') + ' back on the site' if facts['claims'] else plural(faults, 'thing') + ' to look at') \
        + (f', {faults - facts["claims"]} more to look at' if facts['claims'] and faults > facts['claims'] else '')


