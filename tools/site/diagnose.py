def page_pass(base, p):
    """Console errors for one page or figure and, where axe is installed and the page is ours, its WCAG violations."""
    acts = [['wait', 2500]]
    use_axe = AXE.exists() and rel(p) not in THIRD_PARTY
    if use_axe:
        acts += [['eval', AXE.read_text() + ';\n1'], ['eval', AXE_RUN]]
    ev, errs = drive(base + rel(p), acts)
    return errs, (ev[-1] if use_axe and len(ev) == 2 and isinstance(ev[-1], list) else None)


def lighthouse(url):
    r = subprocess.run([str(LIGHTHOUSE), url, '--output=json', '--output-path=stdout', '--quiet',
                        '--chrome-flags=--headless=new --no-sandbox --disable-gpu',
                        '--only-categories=performance,accessibility,best-practices,seo'],
                       capture_output=True, text=True, timeout=240, env={**os.environ, 'CHROME_PATH': CHROME})
    rep = json.loads(r.stdout)
    if rep.get('runtimeError', {}).get('code') not in (None, 'NO_ERROR'):
        raise RuntimeError(rep['runtimeError'].get('message', 'Lighthouse failed'))
    c, a = rep['categories'], rep['audits']
    score = lambda k: None if c.get(k, {}).get('score') is None else round(c[k]['score'] * 100)
    num = lambda k, f: None if a.get(k, {}).get('numericValue') is None else f(a[k]['numericValue'])
    return {'performance': score('performance'), 'accessibility': score('accessibility'), 'best_practices': score('best-practices'),
            'seo': score('seo'), 'lcp_s': num('largest-contentful-paint', lambda v: round(v / 1000, 2)),
            'cls': num('cumulative-layout-shift', lambda v: round(v, 3)), 'tbt_ms': num('total-blocking-time', round)}


def drive(url, actions, reduced=False):
    steps = OUT / f'.steps-{os.getpid()}-{abs(hash((url, reduced, json.dumps(actions)))) % 10**8}.json'
    steps.write_text(json.dumps(actions))
    cmd = ['node', str(DRIVE), url, '--actions', str(steps), '--width', '1440', '--height', '1000'] + (['--reduced'] if reduced else [])
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=240)
    steps.unlink(missing_ok=True)
    out = r.stdout.splitlines()
    evals = [json.loads(l[6:]) for l in out if l.startswith('eval: ')]
    errors = [l for l in out if l.startswith(('console.error', 'console.warning', 'exception', 'Uncaught', 'pageerror'))
              and 'goatcounter: not counting' not in l         # GoatCounter skips 127.0.0.1 on purpose and says so
              and 'kicanvas:parser' not in l]                  # KiCanvas notes KiCad 9/10 fields it skips; it still draws
    if r.returncode and not errors:
        errors = [(r.stderr or 'the driver failed').strip().splitlines()[-1][:300]]
    return evals, errors


def snap(sel):
    """A fingerprint of a card icon's drawn state: every part's box (to half a pixel), opacity and visibility.
    It catches attribute, CSS and SMIL motion alike, since all of them move what is drawn."""
    return ("(() => { const c = document.querySelector(%s); const svg = c && c.querySelector('.icon svg'); if (!svg) return '';"
            " return [...svg.querySelectorAll('g,path,circle,rect,image,line,polygon')].map(e => { const b = e.getBoundingClientRect();"
            " const s = getComputedStyle(e); return [b.x, b.y, b.width, b.height].map(n => Math.round(n * 2)).join(',') + s.opacity.slice(0, 4) + s.visibility[0]; }).join('|'); })()"
            % json.dumps(sel))


