"""Controller comparison figure for the airbrakes page, drawn from the study's own per-flight results.

Usage: python3 -I build_controllers.py <airbrakes>/outputs/compare_hera_200_tuned_runs.csv <out.html>

The runs file holds each of the 200 simulated 6-DOF flights of Hera flown 6 ways: brakes shut (clean), brakes fully
open (full) and the four controllers. A flight counts as reachable when the 2,900 m target lies between its full-brake
and clean apogees, as in the study; the figure plots each controller's apogee miss on those flights and recomputes
the RMS from the rows (3.72, 3.86, 4.04 and 21.39 m, matching the study's summary). Read-only on the study's files.
"""
import csv
import json
import math
import sys
from collections import defaultdict
from pathlib import Path

runs, out = Path(sys.argv[1]), Path(sys.argv[2])
TARGET = 2900.0
ROWS = [('solve', 'Target solve'), ('pi:', 'PI'), ('mpc:', 'MPC'), ('bangbang:', 'Bang-bang')]   # fixed order, not a ranking

by = defaultdict(dict)
for r in csv.DictReader(open(runs)):
    by[int(r['case'])][r['kind']] = r
kinds = {pre: next(k for k in by[0] if k.startswith(pre)) for pre, _ in ROWS}
reach = sorted(c for c, k in by.items() if float(k['full']['apogee_agl']) <= TARGET <= float(k['clean']['apogee_agl']))
low = sum(1 for k in by.values() if float(k['clean']['apogee_agl']) < TARGET)
high = sum(1 for k in by.values() if float(k['full']['apogee_agl']) > TARGET)

rows, stats = [], []
for pre, name in ROWS:
    e = [round(float(by[c][kinds[pre]]['error_m']), 2) for c in reach]
    a = sorted(abs(v) for v in e)
    stats.append({'name': name, 'rms': round(math.sqrt(sum(v * v for v in e) / len(e)), 2),
                  'p95': round(a[math.ceil(0.95 * len(a)) - 1], 1), 'worst': round(a[-1], 1)})
    rows.append(e)
flights = [{'case': c, 'wind': round(float(by[c]['clean']['wind_speed_ms']), 1)} for c in reach]
data = {'rows': rows, 'names': [n for _, n in ROWS], 'stats': stats, 'flights': flights,
        'n': len(by), 'reach': len(reach), 'low': low, 'high': high, 'target': TARGET}

page = r'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Airbrake controllers compared</title>
<!-- Generated by portfolio/figures/airbrakes/build_controllers.py from the study's per-flight results (outputs/compare_hera_200_tuned_runs.csv).
     Chart rules follow the dataviz skill: hairline grid, one hue for one series, direct labels, a table view and a hover readout. -->
<style>
@font-face { font-family: "Sanchez"; src: url("../fonts/sanchez-400-latin.woff2") format("woff2"); font-display: swap; }
:root { --ink: #2E1499; --muted: #5E4FA8; --grid: #ECE9F6; --dot: #4F37C8; --hi: #E8590C; --surface: #FFFFFF; }
* { box-sizing: border-box; }
html, body { margin: 0; background: var(--surface); color: var(--ink); font: 14px/1.45 "Sanchez", Georgia, serif; }
.wrap { padding: 14px 16px 12px; display: grid; gap: 8px; }
h3 { margin: 0; font-size: 13px; font-weight: 400; color: var(--muted); }
svg { display: block; width: 100%; height: auto; overflow: visible; }
.grid line { stroke: var(--grid); stroke-width: 1; }
.zero { stroke: var(--ink); stroke-width: 1; }
.tick { fill: var(--muted); font-size: 11px; font-variant-numeric: tabular-nums; }
.name { fill: var(--ink); font-size: 12.5px; }
.rms { fill: var(--ink); font-size: 12px; font-variant-numeric: tabular-nums; }
.dots circle { fill: var(--dot); fill-opacity: 0.42; }
.ring { fill: none; stroke: var(--hi); stroke-width: 2; }
.hit { fill: transparent; cursor: crosshair; }
svg { touch-action: pan-y; }   /* a finger scrolls the page up and down; a tap or sideways drag picks a flight */
.readout { min-height: 1.45em; margin: 0; font-size: 12.5px; color: var(--ink); font-variant-numeric: tabular-nums; }
@media (max-width: 620px) { .readout { min-height: 2.9em; } }   /* room for the longest readout, so the frame does not grow and shrink while you explore */
@media (max-width: 400px) { .readout { min-height: 4.35em; } }
.sr { position: absolute; width: 1px; height: 1px; overflow: hidden; clip: rect(0 0 0 0); white-space: nowrap; }
th:nth-child(n+2), td:nth-child(n+2) { text-align: right; }   /* numbers line up; their unit is in the headers */
details { font-size: 13px; }
summary { cursor: pointer; color: var(--muted); }
table { border-collapse: collapse; margin-top: 6px; }
th, td { text-align: left; padding: 3px 16px 3px 0; border-bottom: 1px solid var(--grid); font-weight: 400; font-variant-numeric: tabular-nums; }
th { color: var(--muted); }
svg:focus-visible { outline: 2px solid var(--ink); outline-offset: 3px; }
</style>
</head>
<body>
<div class="wrap">
  <h3>Apogee miss on each reachable flight (m above or below the 2,900 m target)</h3>
  <svg id="c" viewBox="0 0 640 250" tabindex="0" role="slider" aria-valuemin="1" aria-valuenow="1" aria-valuetext="No flight picked"></svg>
  <p class="readout" id="ro"></p>
  <details><summary>The four controllers as a table</summary>
    <table><thead><tr><th>Controller</th><th>RMS miss (m)</th><th>95% of flights within (m)</th><th>Worst miss (m)</th></tr></thead><tbody id="tb"></tbody></table>
  </details>
</div>
<script>
const D = __DATA__;
const svg = document.getElementById("c"), ro = document.getElementById("ro");
const NS = "http://www.w3.org/2000/svg";
const el = (t, a, p) => { const e = document.createElementNS(NS, t); for (const k in a) e.setAttribute(k, a[k]); if (p) p.appendChild(e); return e; };
const txt = (p, x, y, s, cls, anchor) => { const t = el("text", { x, y, class: cls, "text-anchor": anchor || "start" }, p); t.textContent = s; return t; };
// Two layouts: wide puts names left and RMS right of each strip; narrow (phones) puts both above it, so text stays readable.
const X0 = -60, X1 = 40, T = 8;
// a steady jitter per flight, so each flight sits at the same height in every row
const jit = D.flights.map((f) => ((Math.sin(f.case * 12.9898) * 43758.5453) % 1 + 1) % 1 - 0.5);
let lay = null, pos = [], rings = [], cur = null;
function render() {
  const narrow = svg.getBoundingClientRect().width < 520;
  if (lay && lay.narrow === narrow) return;
  const W = narrow ? 360 : 640, L = narrow ? 8 : 92, R = narrow ? 8 : 76;
  const LAB = narrow ? 18 : 0, ROW = narrow ? 60 : 52, STRIP = ROW - LAB;
  const sx = (v) => L + (v - X0) / (X1 - X0) * (W - L - R);
  const H = T + ROW * D.rows.length + 26;
  svg.replaceChildren();
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  svg.setAttribute("aria-label", `Apogee miss for each controller on the ${D.reach} reachable flights. RMS: ` + D.stats.map((s) => `${s.name} ${s.rms.toFixed(1)} m`).join(", ") + ". Arrow keys step through the flights.");   // a slider: screen readers say its value text at each step
  const g = el("g", { class: "grid" }, svg);
  for (let v = X0; v <= X1; v += 10) {
    el("line", { x1: sx(v), x2: sx(v), y1: T, y2: T + ROW * D.rows.length }, g);
    if (v % 20 === 0) txt(svg, sx(v), H - 8, (v > 0 ? "+" : v < 0 ? "−" : "") + Math.abs(v) + (v === X1 ? " m" : ""), "tick", v === X1 && narrow ? "end" : "middle");
  }
  el("line", { class: "zero", x1: sx(0), x2: sx(0), y1: T, y2: T + ROW * D.rows.length }, svg);
  const dots = el("g", { class: "dots" }, svg);
  pos = [];
  D.rows.forEach((row, r) => {
    const top = T + ROW * r, cy = top + LAB + STRIP / 2;
    if (narrow) {
      txt(svg, L, top + 13, D.names[r], "name");
      txt(svg, W - R, top + 13, `RMS ${D.stats[r].rms.toFixed(1)} m`, "rms", "end");
    } else {
      txt(svg, L - 10, cy + 4, D.names[r], "name", "end");
      txt(svg, W - R + 8, cy + 4, `RMS ${D.stats[r].rms.toFixed(1)} m`, "rms");
    }
    row.forEach((e, i) => {
      const x = sx(Math.max(X0, Math.min(X1, e))), y = cy + jit[i] * STRIP * 0.62;
      el("circle", { cx: x.toFixed(1), cy: y.toFixed(1), r: 2.6 }, dots);
      pos.push([x, y, r, i]);
    });
  });
  rings = D.rows.map(() => el("circle", { class: "ring", r: 5, visibility: "hidden" }, svg));
  const hit = el("rect", { class: "hit", x: L, y: T, width: W - L - R, height: ROW * D.rows.length }, svg);
  const pick = (ev) => {
    const b = svg.getBoundingClientRect(), x = (ev.clientX - b.left) / b.width * W, y = (ev.clientY - b.top) / b.height * H;
    let best = null, bd = 1e9;
    pos.forEach((p) => { const d = (p[0] - x) ** 2 + (p[1] - y) ** 2; if (d < bd) { bd = d; best = p; } });
    const reach = ev.pointerType === "mouse" ? 400 : 1600;   // a fingertip is less exact than a cursor
    cur = best && bd < reach ? best[3] : null; show(cur);
  };
  hit.addEventListener("pointermove", pick);
  hit.addEventListener("pointerdown", pick);   // a tap fires no pointermove on most phones
  hit.addEventListener("pointerleave", (ev) => { if (ev.pointerType === "mouse") show(null); });   // a tapped flight stays until the next tap
  lay = { narrow, W, H };
  if (cur !== null) show(cur);
}
function show(i) {
  if (i === null) { rings.forEach((c) => c.setAttribute("visibility", "hidden")); ro.textContent = ""; svg.setAttribute("aria-valuetext", "No flight picked"); return; }
  D.rows.forEach((row, r) => {
    const p = pos[r * D.flights.length + i];
    rings[r].setAttribute("cx", p[0].toFixed(1)); rings[r].setAttribute("cy", p[1].toFixed(1)); rings[r].setAttribute("visibility", "visible");
  });
  const f = D.flights[i], m = (v) => (v >= 0 ? "+" : "−") + Math.abs(v).toFixed(1) + " m";
  ro.textContent = `Flight ${f.case + 1} (wind ${f.wind} m/s): ` + D.names.map((n, r) => `${n} ${m(D.rows[r][i])}`).join(" · ");
  svg.setAttribute("aria-valuenow", order.indexOf(i) + 1); svg.setAttribute("aria-valuetext", ro.textContent);
}
render();
new ResizeObserver(render).observe(svg);
// keyboard: left and right step through the flights in order of PI's miss
const order = D.flights.map((_, i) => i).sort((a, b) => D.rows[1][a] - D.rows[1][b]);
svg.setAttribute("aria-valuemax", order.length);
svg.addEventListener("keydown", (ev) => {
  const d = { ArrowRight: 1, ArrowLeft: -1 }[ev.key]; if (!d) return; ev.preventDefault();
  const k = cur === null ? 0 : Math.max(0, Math.min(order.length - 1, order.indexOf(cur) + d)); cur = order[k]; show(cur);
});
svg.addEventListener("blur", () => show(null));
const tb = document.getElementById("tb");
D.stats.forEach((s) => { const tr = document.createElement("tr"); [s.name, s.rms.toFixed(1), s.p95.toFixed(1), s.worst.toFixed(1)].forEach((v) => { const td = document.createElement("td"); td.textContent = v; tr.appendChild(td); }); tb.appendChild(tr); });
</script>
</body>
</html>
'''
out.write_text(page.replace('__DATA__', json.dumps(data, separators=(',', ':'))))
print('wrote', out, {s['name']: s['rms'] for s in stats}, f"reachable {len(reach)} of {len(by)} (low {low}, high {high})")
