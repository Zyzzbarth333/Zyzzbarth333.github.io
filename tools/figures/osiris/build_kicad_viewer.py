"""OSIRIS V0's real KiCad files in KiCanvas, as a figure page for the OSIRIS project page.

Usage: python3 -I build_kicad_viewer.py <osiris-v0 KiCad folder> <kicanvas folder> <site-repo> <fonts folder>
Copies the project, board and six schematic sheets to assets/kicad/osiris-v0/, the KiCanvas viewer and its licence to
assets/vendor/kicanvas/, and writes assets/figures/osiris-v0-kicad.html.

The page opens the board in KiCanvas straight away (Isaac, 19 Nov 2026), with a switch to the schematic; the frame that
holds it loads lazily, so KiCanvas and the files (about 2 MB) arrive only when the figure comes into view. The user approved publishing these files
(13 Nov 2026). They were checked first: no home-folder paths and no email addresses. The only text variables are the
author's name, the board name and the revision, all already public.
KiCanvas (c) 2022 Alethea Katherine Flowers, MIT licence: https://kicanvas.org/, source at
https://github.com/theacodes/kicanvas. It logs warnings for KiCad 9 and 10 fields it does not know, but it draws both
the board and the schematic.

KiCanvas asks Google Fonts for its icon font (Material Symbols) and Nunito when it loads. The site loads nothing from
other servers, so the copy here points that stylesheet at self-hosted files instead. <fonts folder> holds both licences and:
  Material Symbols Outlined, cut down to the icons KiCanvas uses (Apache 2.0): https://github.com/google/material-design-icons
  Nunito, Latin variable font, weights 300 to 700 (SIL OFL 1.1): https://github.com/googlefonts/nunito
Both were downloaded from Google Fonts (https://fonts.google.com/).
"""
import shutil
import sys
from pathlib import Path

src, kc, repo, fonts = (Path(a).expanduser() for a in sys.argv[1:5])
SHEETS = ['osiris-v0.kicad_sch', 'mcu.kicad_sch', 'power.kicad_sch', 'sensors.kicad_sch', 'storage_io.kicad_sch', 'diagnostics.kicad_sch']
FILES = ['osiris-v0.kicad_pro', 'osiris-v0.kicad_pcb'] + SHEETS

dst = repo / 'assets/kicad/osiris-v0'
dst.mkdir(parents=True, exist_ok=True)
for f in FILES:   # LF line endings, as the site repo stores them (.gitattributes), so a rebuild changes nothing
    (dst / f).write_bytes((src / f).read_bytes().replace(b'\r\n', b'\n'))
vendor = repo / 'assets/vendor/kicanvas'
vendor.mkdir(parents=True, exist_ok=True)
GOOGLE = 'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@48,400,0,0&family=Nunito:wght@300;400;500;600;700&display=swap'
js = (kc / 'kicanvas.js').read_text()
assert js.count(GOOGLE) == 1, 'the Google Fonts link in kicanvas.js has changed: check the patch'
js = js.replace(GOOGLE, '../vendor/kicanvas/fonts/fonts.css')   # resolved against the figure page in assets/figures/
(vendor / 'kicanvas.js').write_text('/* KiCanvas (MIT, (c) 2022 Alethea Katherine Flowers; LICENSE.md beside this file), from https://kicanvas.org/,\n'
                                    '   source at https://github.com/theacodes/kicanvas.\n'
                                    '   Changed here: its font stylesheet points at fonts/fonts.css, self-hosted, not at Google Fonts. */\n' + js)
fd = vendor / 'fonts'
fd.mkdir(exist_ok=True)
for f in ('material-symbols-outlined-subset.woff2', 'nunito-latin-300-700.woff2', 'LICENSE-material-symbols.txt', 'OFL-Nunito.txt'):
    shutil.copyfile(fonts / f, fd / f)
(fd / 'fonts.css').write_text('''/* Fonts for KiCanvas, self-hosted, both from Google Fonts.
   Material Symbols Outlined, cut down to the icons KiCanvas uses: Apache 2.0 (LICENSE-material-symbols.txt),
   https://github.com/google/material-design-icons
   Nunito, Latin, weights 300 to 700: SIL OFL 1.1 (OFL-Nunito.txt), https://github.com/googlefonts/nunito */
@font-face { font-family: "Material Symbols Outlined"; font-style: normal; font-weight: 400; font-display: block;
             src: url("material-symbols-outlined-subset.woff2") format("woff2"); }
@font-face { font-family: "Nunito"; font-style: normal; font-weight: 300 700; font-display: swap;
             src: url("nunito-latin-300-700.woff2") format("woff2"); }
''')
shutil.copyfile(kc / 'LICENSE.md', vendor / 'LICENSE.md')
mb = sum((dst / f).stat().st_size for f in FILES) / 1e6 + (vendor / 'kicanvas.js').stat().st_size / 1e6

page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>OSIRIS V0 in KiCad</title>
<!-- Generated by portfolio/figures/osiris/build_kicad_viewer.py. KiCanvas (MIT, (c) 2022 Alethea Katherine Flowers,
     https://kicanvas.org/, source at https://github.com/theacodes/kicanvas) loads with the frame; its licence is at
     ../vendor/kicanvas/LICENSE.md. -->
<style>
@font-face {{ font-family: "Sanchez"; src: url("../fonts/sanchez-400-latin.woff2") format("woff2"); font-display: swap; }}
:root {{ --ink: #2E1499; --muted: #5E4FA8; --grid: #ECE9F6; --surface: #FFFFFF; }}
* {{ box-sizing: border-box; }}
html, body {{ margin: 0; background: var(--surface); color: var(--ink); font: 14px/1.45 "Sanchez", Georgia, serif; }}
.wrap {{ padding: 14px 16px 12px; display: grid; gap: 10px; }}
.bar {{ display: flex; flex-wrap: wrap; align-items: baseline; gap: 4px 18px; margin: 0; }}
button.link {{ font: inherit; color: var(--ink); background: none; border: 0; padding: 4px 0; text-decoration: underline; text-underline-offset: 0.2em; cursor: pointer; }}
button.link[aria-pressed="true"] {{ text-decoration: none; font-weight: 700; }}
button.link:focus-visible {{ outline: 2px solid var(--ink); outline-offset: 3px; }}
.note {{ color: var(--muted); font-size: 13px; margin: 0; }}
.stage {{ position: relative; width: 100%; aspect-ratio: 16 / 10; min-height: 320px; border: 1px solid var(--grid); background: var(--surface); overflow: hidden; }}
.stage.closed {{ aspect-ratio: auto; min-height: 0; padding: 14px 16px; }}   /* until a view is opened: no fourth picture of the board */
.stage img {{ display: block; width: 100%; height: 100%; object-fit: contain; }}
kicanvas-embed {{ display: block; width: 100%; height: 100%; min-width: 0; }}
@media (max-width: 520px) {{ .wrap {{ padding: 10px; }} .stage {{ aspect-ratio: 4 / 5; }} }}
</style>
</head>
<body>
<div class="wrap">
  <p class="bar">
    <button class="link" type="button" data-show="pcb" aria-pressed="true">The board</button>
    <button class="link" type="button" data-show="sch" aria-pressed="false">The schematic</button>
    <span class="note">The real KiCad files, drawn by KiCanvas (about {mb:.1f} MB): drag to pan, scroll to zoom.</span>
  </p>
  <div class="stage" id="stage" aria-live="polite">
    <p class="note" style="padding:12px">Loading the KiCad viewer…</p>
  </div>
</div>
<script>
(function () {{
  var DIR = '../kicad/osiris-v0/';
  var FILES = {{ pcb: ['osiris-v0.kicad_pro', 'osiris-v0.kicad_pcb'], sch: ['osiris-v0.kicad_pro'].concat({SHEETS!r}) }};
  var stage = document.getElementById('stage');
  var buttons = [].slice.call(document.querySelectorAll('[data-show]'));
  var loading = null;
  function load() {{
    if (!loading) loading = new Promise(function (ok, fail) {{
      var s = document.createElement('script');
      s.type = 'module'; s.src = '../vendor/kicanvas/kicanvas.js';
      s.onload = ok; s.onerror = fail;
      document.head.appendChild(s);
    }});
    return loading;
  }}
  // KiCanvas's toolbar icon buttons have no accessible name: give each one its own button name, read as words
  function label(root) {{
    if (root.shadowRoot) label(root.shadowRoot);   // the viewer's own shadow root first
    (root.querySelectorAll ? root.querySelectorAll('*') : []).forEach(function (el) {{
      if (el.shadowRoot) label(el.shadowRoot);
      if (el.tagName === 'KC-UI-BUTTON' && el.getAttribute('name')) {{
        var words = el.getAttribute('title') || el.getAttribute('name').replace(/_/g, ' ');
        var b = el.shadowRoot && el.shadowRoot.querySelector('button');
        if (b && !b.getAttribute('aria-label')) b.setAttribute('aria-label', words);
      }}
    }});
  }}
  // it also warns about KiCad 10 fields it doesn't know (the drawing is right); keep those out of the console
  var warn = console.warn;
  console.warn = function (first) {{ if (typeof first === 'string' && first.indexOf('kicanvas') >= 0) return; return warn.apply(console, arguments); }};
  function show(which) {{
    buttons.forEach(function (b) {{ b.setAttribute('aria-pressed', String(b.dataset.show === which)); }});
    var wait = document.createElement('p'); wait.className = 'note'; wait.style.padding = '12px';
    wait.textContent = 'Loading the KiCad viewer…';
    stage.classList.remove('closed');
    stage.replaceChildren(wait);
    load().then(function () {{
      var e = document.createElement('kicanvas-embed');
      e.setAttribute('controls', window.innerWidth < 700 ? 'basic' : 'full');   // the full sidebar needs about 650 px
      e.setAttribute('aria-label', which === 'pcb' ? 'OSIRIS V0 board in KiCanvas' : 'OSIRIS V0 schematic in KiCanvas');
      FILES[which].forEach(function (f) {{
        var s = document.createElement('kicanvas-source'); s.setAttribute('src', DIR + f); e.appendChild(s);
      }});
      stage.replaceChildren(e);
      [300, 1000, 2500, 5000, 8000].forEach(function (t) {{ setTimeout(function () {{ label(e); }}, t); }});
    }}).catch(function () {{
      wait.textContent = 'The viewer could not load. The KiCad files are in assets/kicad/osiris-v0/.';
    }});
  }}
  buttons.forEach(function (b) {{ b.addEventListener('click', function () {{ show(b.dataset.show); }}); }});
  show('pcb');   // the board opens straight away (Isaac, 19 Nov 2026); the frame itself loads lazily on the page
}})();
</script>
</body>
</html>
'''
out = repo / 'assets/figures/osiris-v0-kicad.html'
out.write_text(page)
print('wrote', out, f'{mb:.1f} MB of viewer and files')
